// ===================== 拼音与索引（懒构建） =====================

/** 单字 → 无声调拼音 的缓存，避免重复计算。 */
const _tonelessCache = new Map<string, string>();

/**
 * 取单字的无声调拼音（多音字取第一个读音）。
 * 例如 `toneless('重')` => 'chong'。
 */
export function toneless(char: string): string {
  if (char.length === 0) return '';
  const cached = _tonelessCache.get(char);
  if (cached !== undefined) return cached;
  const result = pinyin(char, { toneType: 'none', type: 'array' })[0] ?? char;
  _tonelessCache.set(char, result);
  return result;
}

/** 两字是否同音（忽略声调）。任一为空串时返回 false。 */
export function isHomophone(a: string, b: string): boolean {
  if (a.length === 0 || b.length === 0) return false;
  return toneless(a) === toneless(b);
}

// 首字索引（懒构建）
let _charIndex: ReadonlyMap<string, readonly string[]> | null = null;
function buildCharIndex(): ReadonlyMap<string, readonly string[]> {
  const m = new Map<string, string[]>();
  for (const idiom of IDIOMS) {
    const key = idiom.charAt(0);
    const bucket = m.get(key);
    if (bucket) bucket.push(idiom);
    else m.set(key, [idiom]);
  }
  const ro = new Map<string, readonly string[]>();
  for (const [k, v] of m) ro.set(k, v);
  return ro;
}
function charIndex(): ReadonlyMap<string, readonly string[]> {
  if (_charIndex === null) _charIndex = buildCharIndex();
  return _charIndex;
}

// 首字无声调拼音索引（懒构建）
let _pinyinIndex: ReadonlyMap<string, readonly string[]> | null = null;
function buildPinyinIndex(): ReadonlyMap<string, readonly string[]> {
  const m = new Map<string, string[]>();
  for (const idiom of IDIOMS) {
    const key = toneless(idiom.charAt(0));
    const bucket = m.get(key);
    if (bucket) bucket.push(idiom);
    else m.set(key, [idiom]);
  }
  const ro = new Map<string, readonly string[]>();
  for (const [k, v] of m) ro.set(k, v);
  return ro;
}
function pinyinIndex(): ReadonlyMap<string, readonly string[]> {
  if (_pinyinIndex === null) _pinyinIndex = buildPinyinIndex();
  return _pinyinIndex;
}

/**
 * 首字 → 成语列表。首次访问时才遍历 `IDIOMS` 建表并缓存。
 * 保持 `ReadonlyMap` 具名导出以满足契约，内部用 getter 实现懒加载。
 */
export const FIRST_CHAR_INDEX: ReadonlyMap<string, readonly string[]> = {
  get size() { return charIndex().size; },
  has(key: string) { return charIndex().has(key); },
  get(key: string) { return charIndex().get(key); },
  keys() { return charIndex().keys(); },
  values() { return charIndex().values(); },
  entries() { return charIndex().entries(); },
  [Symbol.iterator]() { return charIndex().entries(); },
  forEach(
    cb: (value: readonly string[], key: string, map: ReadonlyMap<string, readonly string[]>) => void,
    thisArg?: unknown,
  ): void {
    charIndex().forEach(
      cb as (v: readonly string[], k: string, m: ReadonlyMap<string, readonly string[]>) => void,
      thisArg,
    );
  },
};

/**
 * 首字无声调拼音 → 成语列表。首次访问时才建表并缓存（依赖 `toneless`）。
 */
export const FIRST_PINYIN_INDEX: ReadonlyMap<string, readonly string[]> = {
  get size() { return pinyinIndex().size; },
  has(key: string) { return pinyinIndex().has(key); },
  get(key: string) { return pinyinIndex().get(key); },
  keys() { return pinyinIndex().keys(); },
  values() { return pinyinIndex().values(); },
  entries() { return pinyinIndex().entries(); },
  [Symbol.iterator]() { return pinyinIndex().entries(); },
  forEach(
    cb: (value: readonly string[], key: string, map: ReadonlyMap<string, readonly string[]>) => void,
    thisArg?: unknown,
  ): void {
    pinyinIndex().forEach(
      cb as (v: readonly string[], k: string, m: ReadonlyMap<string, readonly string[]>) => void,
      thisArg,
    );
  },
};

/** 是否收录在库中（内部用 `Set` 加速查找）。 */
let _knownSet: Set<string> | null = null;
function knownSet(): Set<string> {
  if (_knownSet === null) {
    _knownSet = new Set<string>();
    for (const idiom of IDIOMS) _knownSet.add(idiom);
  }
  return _knownSet;
}

/** 是否收录在库中。 */
export function isKnownIdiom(text: string): boolean {
  return knownSet().has(text);
}

/**
 * 取以 `char` 开头的成语；`allowHomophone` 为 true 时，同音字开头的也算。
 * 结果去重后返回副本（不暴露内部数组引用）。
 */
export function getIdiomsStartingWith(char: string, allowHomophone = false): string[] {
  const exact = FIRST_CHAR_INDEX.get(char);
  if (!allowHomophone) {
    return exact ? [...exact] : [];
  }
  const byPinyin = FIRST_PINYIN_INDEX.get(toneless(char));
  const out = new Set<string>(exact ?? []);
  if (byPinyin) {
    for (const idiom of byPinyin) out.add(idiom);
  }
  return [...out];
}
