// 本文件由站长（agent）手动维护：从第三方表单导出真实意见后，挑选用例粘贴到此。
//
// 维护流程（站长视角，三步）：
//   1. 去金数据 / 腾讯问卷后台，看新提交的意见。
//   2. 挑一条值得公开的，把「昵称 / 内容」抄到下面的数组里，再补一句 reply（站长回应）。
//   3. 保存 → 重新构建部署。页面「站长回应区」就会出现这条。
//
// 注意：
//   - 这里的内容会**原样公开**在网站上，粘贴前请自行脱敏（去掉手机号、邮箱、真实姓名等）。
//   - id 只要在本数组内唯一即可，随手写 'r1' / 'r2' / '2024-06-01-a' 都行。
//   - reply 和 date 都是可选的：没写 reply 就只显示原始意见；没写 date 就不显示日期。
//   - 数组为空时，页面会显示「还没有回应，欢迎来提~」的空状态，不会报错。

/** 一条「访客意见 + 站长回应」的展示条目（纯静态数据，无任何网络来源）。 */
export interface CommunityResponse {
  /** 条目唯一标识，仅用于 React key，本数组内唯一即可 */
  id: string;
  /** 访客昵称（站长手工填写，建议脱敏） */
  nickname: string;
  /** 访客提出的意见原文（站长手工摘录） */
  content: string;
  /** 站长的公开回应；留空则该条只展示意见本身 */
  reply?: string;
  /** 展示用日期字符串，如 '2024-06-01'；留空则不展示 */
  date?: string;
}

